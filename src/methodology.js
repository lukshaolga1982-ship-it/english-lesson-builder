export function isMovementStage(name = '') {
  return /физкульт|двигательн|movement/i.test(name);
}

export function resolveEnabledStages(stages = [], form = {}) {
  const mode = form.physicalBreakMode || (form.physicalMinute === false ? 'Не добавлять' : 'Добавить');
  let next = [...stages];
  if (mode === 'Не добавлять') return next.filter((name) => !isMovementStage(name));
  if (mode === 'Добавить' && !next.some(isMovementStage)) {
    const insertAt = Math.max(1, Math.floor(next.length / 2));
    next.splice(insertAt, 0, 'Двигательная пауза / физкультминутка');
  }
  return next;
}

export function findStageIndexForVariant(kind, stages = []) {
  const names = stages.map((s) => String(s?.name || ''));
  if (kind === 'opening') {
    let index = names.findIndex((name) => /мотивац|целеполаг/i.test(name));
    if (index < 0) index = names.findIndex((name) => /актуализац/i.test(name));
    if (index < 0) index = names.findIndex((name) => /организацион/i.test(name));
    return index;
  }
  if (kind === 'movement') return names.findIndex((name) => isMovementStage(name));
  if (kind === 'reflection') return names.findIndex((name) => /рефлекс/i.test(name));
  return -1;
}
